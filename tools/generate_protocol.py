#!/usr/bin/env python3
"""Deterministic .proto generation from the supplied, deduplicated runtime schema.

The archive's split proto files omit cross-package imports and use incorrect
service names. Use its runtime schema instead, preserving field numbers/types.
No code from the archive is executed. Unknown fields remain opaque bytes.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'reference/protocol/schema.json'
TARGET = ROOT / 'core/protocol/src/main/proto/bale.proto'
SCALARS = set('int32 int64 uint32 uint64 sint32 sint64 fixed32 fixed64 sfixed32 sfixed64 float double bool string bytes'.split())


def render(schema):
    messages = schema['messages']
    lines = ['// Generated by tools/generate_protocol.py. Do not edit.',
             '// Source: bale-start.zip / bale-client/baleclient/schema.json',
             'syntax = "proto3";', 'package bale.recovered;',
             'option java_package = "ai.bale.client.protocol";',
             'option java_multiple_files = true;',
             'option java_outer_classname = "BaleSchema";',
             'import "google/protobuf/wrappers.proto";',
             'import "google/protobuf/timestamp.proto";', '']
    for name, fields in sorted(messages.items()):
        if name.startswith('google.protobuf.'):
            continue
        lines.append(f'message {name} {{')
        used = set()
        for number, (field, kind, repeated) in sorted(fields.items(), key=lambda f: int(f[0])):
            assert kind in SCALARS or kind in messages or kind.startswith('google.protobuf.'), kind
            if field in used:
                field = f'{field}_{number}'
            used.add(field)
            lines.append(f'  {"repeated " if repeated else ""}{kind} {field} = {number};')
        lines += ['}', '']
    # Service full names are preserved in schema.json. Do not generate misleading
    # gRPC stubs: Bale uses custom WebSocket routing, not native gRPC transport.
    return '\n'.join(lines).rstrip() + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    schema = json.loads(SOURCE.read_text())
    result = render(schema)
    if args.check:
        assert TARGET.read_text() == result, 'Run python3 tools/generate_protocol.py'
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(result)
    print(f"{len(schema['messages'])} runtime message types; "
          f"{len(schema['services'])} services; "
          f"{sum(map(len, schema['services'].values()))} RPCs")


if __name__ == '__main__':
    main()
